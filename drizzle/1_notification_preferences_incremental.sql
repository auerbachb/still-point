-- Bootstrap migration: notification_preferences with its full current definition,
-- so that `npm run db:migrate` can bootstrap a fresh database again (issue #858).
-- Extends the #535 bootstrap (0_core_tables_incremental.sql), which is applied
-- and append-only, so this is a separate file rather than an edit to it.
--
-- Filename convention: a single leading digit + underscore sorts before all
-- letter-prefixed filenames under a plain lexicographic `.sort()`, yet is NOT
-- matched by the /^\d{4}_/ exclusion. `1_` runs after 0_core_tables_incremental.sql
-- (which creates "users", the FK target below) and before
-- notification_preferences_345_incremental.sql (which first created this table).
--
-- Related: #316 (e2e ephemeral-branch plan relies on db:migrate for fresh DBs),
-- #835 (where the hazard was found).
--
-- ORDERING HAZARD COVERAGE: two applied files sort before the file that adds
-- the column they need:
--   notification_preferences_dispatch_idx_531_incremental.sql indexes
--     failure_reason_reminder_enabled, added by
--     notification_preferences_failure_reason_441_incremental.sql;
--   notification_preferences_session_active_709_incremental.sql sets the default
--     of suppress_during_session, added by
--     notification_preferences_suppress_during_session_431_incremental.sql.
-- This file creates the table with every current column, so both find their
-- column on a fresh database. The later ADD COLUMN IF NOT EXISTS files are then
-- no-ops, and the final defaults below stand: suppress_during_session is
-- DEFAULT true (#709), not the false that #431 first added it with.
--
-- Left to the files that own them, which run cleanly after this one:
-- idx_notification_preferences_dispatch (created by _345, then dropped and
-- recreated with all five columns by _531) and the notification_dispatches
-- table (_345). The constraint names match _345, whose FK guard looks the FK up
-- by name and so skips it.
--
-- IDEMPOTENCY: a single CREATE TABLE IF NOT EXISTS. On prod/preview, where the
-- table already exists, this file is a pure no-op (it never alters an existing
-- table) that records exactly one new schema_migrations ledger row.
--
-- APPEND-ONLY: Do not edit this file after it is applied (checksum ledger rule;
-- see drizzle/README.md and incidents #368/#370). Future column changes belong
-- in new idempotent incremental files, not edits here.

CREATE TABLE IF NOT EXISTS "notification_preferences" (
  "user_id" uuid PRIMARY KEY NOT NULL,
  "push_enabled" boolean DEFAULT false NOT NULL,
  "daily_reminder_enabled" boolean DEFAULT false NOT NULL,
  "miss_a_day_enabled" boolean DEFAULT false NOT NULL,
  "failure_reason_reminder_enabled" boolean DEFAULT false NOT NULL,
  "friend_request_notifications_enabled" boolean DEFAULT true NOT NULL,
  "suppress_during_session" boolean DEFAULT true NOT NULL,
  "session_active_until" timestamp with time zone,
  "daily_reminder_time" varchar(5) DEFAULT '09:00' NOT NULL,
  "daily_reminder_frequency" varchar(20) DEFAULT 'daily' NOT NULL,
  "quiet_hours_start" varchar(5),
  "quiet_hours_end" varchar(5),
  "call_opt_in" boolean DEFAULT false NOT NULL,
  "call_phone_number" varchar(20),
  "call_consent_at" timestamp with time zone,
  "call_window_start" varchar(5),
  "call_window_stop" varchar(5),
  "tz" varchar(64) DEFAULT 'UTC' NOT NULL,
  "created_at" timestamp with time zone DEFAULT now() NOT NULL,
  "updated_at" timestamp with time zone DEFAULT now() NOT NULL,
  CONSTRAINT "notification_preferences_user_id_users_id_fk"
    FOREIGN KEY ("user_id") REFERENCES "public"."users"("id")
    ON DELETE cascade ON UPDATE no action,
  CONSTRAINT "notification_preferences_frequency_allowed"
    CHECK ("daily_reminder_frequency" in ('daily', 'every_other', 'weekly'))
);
